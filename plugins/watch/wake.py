def digest_prompt(scene: Scene, fresh: int) -> str:
    seen = (f"待看列表里有 {fresh} 条你还没看过的事件。没有哪一条急，只是到时间请你过一眼：值得做点什么就做，不值得就划掉。过完之后" if fresh
            else "没有事件在催你。上次醒来之后你和他说过话，现在他停下来了，")
    reason = seen + _RECAP + "对话里没有要收尾的，才想一想记忆里有没有哪件他在意、你够得着、又有一阵没看的事，先看足迹里有没有你已经反复去的地方（每回都记着新东西，或者每回只是确认没变）：有，这一回就不要再只是去看一眼，把它接成来源（办法见技能 watch），让新的自己进来，然后在专题里写明已经接了。再对着足迹挑一处没去过或很久没去的，去看一眼，把看到的记进当天的见闻；没有变化不用告诉他。一条路试一两次走不通就记下来换下一件，不要换着说法反复试；该做的做完就结束。"
    return "\n\n".join((_HEAD, reason, _scene(scene)))


def review_prompt(scene: Scene, expiring: Sequence[str]) -> str:
    soon = "三天内到期的嘱托：\n" + "\n".join(expiring) if expiring else "没有即将到期的嘱托。"
    return "\n\n".join((_HEAD, _REVIEW, soon, _scene(scene)))

